# On-the-fly analyses as cached targets.
#
# The main pipeline lives in <results_dir>/_targets. Interactive analyses live in
# a *separate* store, <results_dir>/_targets_interactive, so exploring never
# invalidates (or races with) the production run. Each analysis spec is one
# target named "an_<hash>", all depending on one file target: the merged object.
# Consequences:
#   * the same analysis asked twice is a cache hit (targets skips it);
#   * the history survives restarts and is shared between sessions;
#   * replacing the merged object invalidates every analysis built from it;
#   * a failed analysis is recorded (error = "continue") without blocking others.

#' Locations of the interactive targets store
#' @param results_dir Pipeline results directory.
#' @return List with \code{dir}, \code{store}, \code{specs}, \code{script}.
#' @keywords internal
.interactive_paths <- function(results_dir) {
  dir <- file.path(results_dir, "_targets_interactive")
  list(dir = dir, store = file.path(dir, "store"), specs = file.path(dir, "specs"),
       script = file.path(dir, "_targets.R"), context = file.path(dir, "context.rds"))
}

.require_targets <- function() {
  if (!requireNamespace("targets", quietly = TRUE)) {
    stop("Interactive analyses are run as targets. Install package 'targets'.", call. = FALSE)
  }
  if (!requireNamespace("digest", quietly = TRUE)) {
    stop("Package 'digest' is required for interactive analyses.", call. = FALSE)
  }
}

#' Run one spec file against an object (the command each analysis target executes)
#' @param spec_file Path to an \code{.rds} holding a [sparks_spec()].
#' @param object_path Path to the Seurat \code{.rds}.
#' @return A \code{sparks_analysis}.
#' @keywords internal
#' @export
sparks_run_spec_file <- function(spec_file, object_path) {
  sparks_run_spec(readRDS(spec_file), object_path)
}

#' Queue an analysis spec in the interactive store
#'
#' Saves the spec (idempotent: the id is a content hash). It is run by
#' [sparks_interactive_run()].
#'
#' @param results_dir Pipeline results directory.
#' @param spec A [sparks_spec()].
#' @param object_path Seurat object the analysis runs on.
#' @return The spec id.
#' @export
sparks_interactive_submit <- function(results_dir, spec, object_path) {
  stopifnot(inherits(spec, "sparks_spec"))
  p <- .interactive_paths(results_dir)
  make_dir(p$specs)
  spec$object <- normalizePath(object_path, winslash = "/", mustWork = TRUE)
  # The object path is not part of the content hash, so the same selection on two
  # different objects must not collide: fold it into the id.
  spec$id <- digest::digest(list(spec$id, spec$object), algo = "xxhash64")
  saveRDS(spec, file.path(p$specs, paste0(spec$id, ".rds")))
  saveRDS(list(object = spec$object, updated = Sys.time()), p$context)
  spec$id
}

.interactive_write_script <- function(results_dir, object_path) {
  p <- .interactive_paths(results_dir)
  make_dir(p$dir)
  lines <- c(
    "# Generated by SPARKS (sparks_interactive_run). Edits are overwritten.",
    "targets::tar_option_set(error = \"continue\", memory = \"transient\", garbage_collection = TRUE)",
    sprintf("object_path <- %s", deparse(normalizePath(object_path, winslash = "/", mustWork = TRUE))),
    sprintf("spec_files <- list.files(%s, pattern = \"[.]rds$\", full.names = TRUE)", deparse(normalizePath(p$specs, winslash = "/", mustWork = FALSE))),
    "specs <- lapply(spec_files, readRDS)",
    "specs <- Filter(function(s) identical(normalizePath(s$object, winslash = \"/\", mustWork = FALSE), normalizePath(object_path, winslash = \"/\", mustWork = FALSE)), specs)",
    "targets_list <- list(targets::tar_target_raw(\"object_file\", quote(object_path), format = \"file\"))",
    "for (s in specs) {",
    "  targets_list[[length(targets_list) + 1L]] <- targets::tar_target_raw(",
    "    paste0(\"an_\", s$id),",
    "    substitute(SPARKS::sparks_run_spec_file(SPEC_FILE, object_file),",
    "               list(SPEC_FILE = file.path(dirname(spec_files[1]), paste0(s$id, \".rds\")))))",
    "}",
    "targets_list"
  )
  writeLines(lines, p$script)
  invisible(p$script)
}

#' Run queued interactive analyses
#'
#' Builds every analysis that is not already cached. With \code{background =
#' TRUE} the run happens in a fresh R process (needs SPARKS installed, not
#' just loaded), which is how the Shiny explorer keeps its UI responsive.
#'
#' @param results_dir Pipeline results directory.
#' @param object_path Seurat object the queued analyses refer to.
#' @param background Run in a separate R process (\code{callr}) and block until done.
#' @return A data frame from [sparks_interactive_status()].
#' @export
sparks_interactive_run <- function(results_dir, object_path, background = FALSE) {
  .require_targets()
  p <- .interactive_paths(results_dir)
  make_dir(p$specs)
  script <- .interactive_write_script(results_dir, object_path)
  args <- list(script = script, store = p$store, reporter = "silent",
               callr_function = if (isTRUE(background) && requireNamespace("callr", quietly = TRUE)) callr::r else NULL)
  # tar_make() (even in-process) must not stop the caller when one analysis fails.
  tryCatch(do.call(targets::tar_make, args), error = function(e) {
    # An error inside a target is recorded in the store; surface only infrastructure errors.
    if (!grepl("target|error", conditionMessage(e), ignore.case = TRUE)) stop(e)
  })
  sparks_interactive_status(results_dir)
}

#' History of interactive analyses
#' @param results_dir Pipeline results directory.
#' @return Data frame: \code{id}, \code{type}, \code{label}, \code{created},
#'   \code{status} (\code{built} / \code{error} / \code{pending}), \code{error}, \code{seconds}.
#' @export
sparks_interactive_status <- function(results_dir) {
  p <- .interactive_paths(results_dir)
  empty <- data.frame(id = character(), type = character(), label = character(),
                      created = character(), status = character(), error = character(),
                      seconds = numeric(), object = character(), stringsAsFactors = FALSE)
  files <- if (dir.exists(p$specs)) list.files(p$specs, pattern = "\\.rds$", full.names = TRUE) else character()
  if (!length(files)) return(empty)
  specs <- lapply(files, function(f) tryCatch(readRDS(f), error = function(e) NULL))
  specs <- Filter(Negate(is.null), specs)
  if (!length(specs)) return(empty)
  out <- data.frame(
    id = vapply(specs, function(s) s$id, character(1)),
    type = vapply(specs, function(s) s$type, character(1)),
    label = vapply(specs, function(s) s$label, character(1)),
    created = vapply(specs, function(s) s$created %||% "", character(1)),
    object = vapply(specs, function(s) s$object %||% "", character(1)),
    status = "pending", error = NA_character_, seconds = NA_real_, stringsAsFactors = FALSE
  )
  if (dir.exists(p$store) && requireNamespace("targets", quietly = TRUE)) {
    meta <- tryCatch(targets::tar_meta(store = p$store, fields = c("name", "error", "seconds"),
                                       complete_only = FALSE), error = function(e) NULL)
    if (is.data.frame(meta) && nrow(meta)) {
      m <- meta[match(paste0("an_", out$id), meta$name), , drop = FALSE]
      has <- !is.na(m$name)
      failed <- has & !is.na(m$error) & nzchar(m$error)
      exists <- file.exists(file.path(p$store, "objects", paste0("an_", out$id)))
      out$status[has & exists & !failed] <- "built"
      out$status[failed] <- "error"
      out$error[failed] <- m$error[failed]
      out$seconds[has] <- m$seconds[has]
    }
  }
  out <- out[order(out$created, decreasing = TRUE), , drop = FALSE]
  rownames(out) <- NULL
  out
}

#' Read the result of a finished interactive analysis
#' @param results_dir Pipeline results directory.
#' @param id Analysis id from [sparks_interactive_status()].
#' @return A \code{sparks_analysis}.
#' @export
sparks_interactive_result <- function(results_dir, id) {
  .require_targets()
  p <- .interactive_paths(results_dir)
  targets::tar_read_raw(paste0("an_", id), store = p$store)
}

#' Delete an interactive analysis (spec and cached result)
#' @param results_dir Pipeline results directory.
#' @param id Analysis id.
#' @return \code{TRUE} if something was removed, invisibly.
#' @export
sparks_interactive_delete <- function(results_dir, id) {
  p <- .interactive_paths(results_dir)
  a <- unlink(file.path(p$specs, paste0(id, ".rds")))
  b <- unlink(file.path(p$store, "objects", paste0("an_", id)))
  invisible(a == 0L && (file.exists(file.path(p$specs, paste0(id, ".rds"))) == FALSE))
}

#' Tables produced by interactive analyses (for the report)
#' @param results_dir Pipeline results directory.
#' @return List of \code{list(id, label, kind, table)}; only built analyses.
#' @keywords internal
.interactive_tables <- function(results_dir) {
  st <- tryCatch(sparks_interactive_status(results_dir), error = function(e) NULL)
  if (is.null(st) || !nrow(st)) return(list())
  st <- st[st$status == "built", , drop = FALSE]
  out <- list()
  for (i in seq_len(nrow(st))) {
    res <- tryCatch(sparks_interactive_result(results_dir, st$id[[i]]), error = function(e) NULL)
    if (is.null(res)) next
    tab <- if (!is.null(res$table)) res$table else if (!is.null(res$markers)) res$markers else NULL
    if (is.data.frame(tab) && nrow(tab)) {
      out[[length(out) + 1L]] <- list(id = st$id[[i]], label = st$label[[i]], type = st$type[[i]], table = tab)
    }
  }
  out
}
